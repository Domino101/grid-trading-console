import os
import asyncio
import logging
from typing import List, Dict, Any, Optional
import httpx
from dotenv import load_dotenv

# Setup logging
logger = logging.getLogger("HermesGridClient")
if not logger.handlers:
    handler = logging.StreamHandler()
    formatter = logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s')
    handler.setFormatter(formatter)
    logger.addHandler(handler)
    logger.setLevel(logging.INFO)

# Load environment variables if available
load_dotenv()


class HermesGridClient:
    """Hermes Agent 調用網格 API 的最小範例 (Strict Compliance)"""
    
    def __init__(self, base_url="http://localhost:8001", token="xxx"):
        self.base = base_url
        
        # Auto-resolve token if default/placeholder is used
        resolved_token = token
        if resolved_token == "xxx" or not resolved_token:
            resolved_token = os.environ.get("GRID_API_TOKEN")
            if not resolved_token:
                # Fallback to reading from .grid_api_token file if exists
                token_file = os.path.join(os.getcwd(), ".grid_api_token")
                if os.path.exists(token_file):
                    try:
                        with open(token_file, "r", encoding="utf-8") as f:
                            resolved_token = f.read().strip()
                    except Exception as e:
                        logger.warning(f"Failed to read token file: {e}")
                        
        self.headers = {"Authorization": f"Bearer {resolved_token}"}
    
    async def is_system_ready(self) -> bool:
        """Step 1: 檢查系統是否可操作"""
        r = await httpx.AsyncClient().get(
            f"{self.base}/api/v1/system/health", 
            headers=self.headers
        )
        health = r.json()
        return health["can_accept_new_grid"]
    
    async def create_neutral_grid(
        self, symbol: str, lower: float, upper: float, 
        interval: float, amount: float
    ) -> dict:
        """Step 2: 一鍵建立中性網格（最常用場景）"""
        r = await httpx.AsyncClient().post(
            f"{self.base}/api/v1/grids",
            json={
                "symbol": symbol,
                "exchange": "binance",
                "grid_type": "neutral",
                "lower_price": lower,
                "upper_price": upper,
                "grid_interval": interval,
                "order_amount": amount,
                "leverage": 50,
                "margin_mode": "cross",
                "quantity_precision": 4,
                "price_decimals": 2,
                "auto_start": True,
                "metadata": {"source": "hermes"}
            },
            headers=self.headers,
            timeout=30
        )
        return r.json()
    
    async def stop_grid(self, grid_id: str) -> dict:
        """Step 3: 停止網格"""
        r = await httpx.AsyncClient().post(
            f"{self.base}/api/v1/grids/{grid_id}/stop",
            headers=self.headers
        )
        return r.json()
    
    async def get_pnl_summary(self) -> dict:
        """Step 4: 查詢全局 PnL"""
        r = await httpx.AsyncClient().get(
            f"{self.base}/api/v1/grids/summary",
            headers=self.headers
        )
        return r.json()


class HermesDecision:
    """Helper representing a decision generated by the Hermes AI agent"""
    def __init__(self, action: str, params: Optional[Dict[str, Any]] = None, grid_id: Optional[str] = None):
        self.action = action  # "create", "stop", or "hold"
        self.params = params or {}
        self.grid_id = grid_id

    def __repr__(self) -> str:
        return f"HermesDecision(action={self.action}, params={self.params}, grid_id={self.grid_id})"


class HermesGridController:
    """Hermes Agent 控制網格的標準流程 (Strict Compliance)"""
    
    def __init__(self, grid_api_url: str, api_token: str):
        self.client = HermesGridClient(grid_api_url, api_token)
    
    async def ai_analyze(self, summary: dict) -> List[HermesDecision]:
        """AI 研判決策 — 由子類覆寫或實作規則引擎
        
        在此基礎類別中，預設回傳空的決策列表（不進行任何操作）。
        """
        logger.info(f"Analyzing system summary: {summary['total_grids']} grids registered.")
        return []

    async def monitor_loop(self):
        """主監控循環 — 建議 15-30 分鐘一次"""
        while True:
            try:
                # Step 1: 檢查系統健康
                if not await self.client.is_system_ready():
                    logger.warning("System health is degraded/unhealthy. Sleeping for 15 minutes...")
                    await asyncio.sleep(900)  # 15 min
                    continue
                
                # Step 2: 取得當前運行狀態
                summary = await self.client.get_pnl_summary()
                
                # Step 3: AI 分析 — 是否需要調整
                decisions = await self.ai_analyze(summary)
                
                # Step 4: 執行決策
                for decision in decisions:
                    if decision.action == "create":
                        logger.info(f"Executing decision: Create Neutral Grid {decision.params.get('symbol')}")
                        await self.client.create_neutral_grid(**decision.params)
                    elif decision.action == "stop":
                        logger.info(f"Executing decision: Stop Grid {decision.grid_id}")
                        await self.client.stop_grid(decision.grid_id)
                
                logger.info("Monitor run completed successfully. Sleeping for 30 minutes...")
                await asyncio.sleep(1800)  # 30 min
            except Exception as e:
                logger.error(f"Error in monitor loop: {e}", exc_info=True)
                # Avoid tight loop in case of severe errors
                await asyncio.sleep(60)
