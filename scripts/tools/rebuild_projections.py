#!/usr/bin/env python3
"""P3-4: Rebuild position projections from canonical facts (events + fills).

Disaster-recovery tool: after projection loss (bot_positions rows deleted /
corrupted), this rebuilds each bot's projection by folding the canonical
timeline.  bot_snapshots / grid_runtime_* are display projections and are
regenerated by the next engine heartbeat, so they are not written here.

Usage:
    python scripts/tools/rebuild_projections.py [--bot-id X] [--db path] [--execute]

Default is dry-run (prints what would be written); --execute performs the
OCC-safe upsert.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time

_REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from core.infrastructure.database.event_fold import diff_projection, rebuild_position  # noqa: E402
from core.infrastructure.database.ledger_repository import LedgerRepository  # noqa: E402
from core.infrastructure.database.models import BotPosition  # noqa: E402


def rebuild(repo: LedgerRepository, bot_id: str, execute: bool) -> dict:
    store = repo.store
    if store.get_bot(bot_id) is None:
        return {"bot_id": bot_id, "status": "bot_not_found"}
    rebuilt = rebuild_position(store, bot_id)
    rebuilt.updated_at = time.time()
    stored = store.get_position(bot_id)
    diffs = diff_projection(stored, rebuilt) if stored else {}
    if execute:
        expected = stored.version if stored else 1
        ok = store.update_position_occ(bot_id, rebuilt, expected_version=expected)
        if not ok:
            # lost a race: retry once against the fresh version
            stored = store.get_position(bot_id)
            ok = bool(store.update_position_occ(bot_id, rebuilt, expected_version=stored.version)) if stored else False
        return {"bot_id": bot_id, "status": "rebuilt" if ok else "occ_conflict", "diffs": diffs}
    return {"bot_id": bot_id, "status": "dry_run", "diffs": diffs}


def main() -> int:
    parser = argparse.ArgumentParser(description="Rebuild bot_positions from facts+events (P3-4)")
    parser.add_argument("--bot-id", default=None, help="One bot; omitted = all bots")
    parser.add_argument("--db", default=None, help="SQLite path (ignored when DATABASE_URL is set)")
    parser.add_argument("--execute", action="store_true", help="Write rebuilt projections (default dry-run)")
    args = parser.parse_args()

    repo = LedgerRepository(args.db)
    bot_ids = [args.bot_id] if args.bot_id else [b.bot_id for b in repo.get_all_bots()]
    if not bot_ids:
        print("（沒有任何 bot）")
        return 0

    results = [rebuild(repo, bid, args.execute) for bid in bot_ids]
    rebuilt = sum(1 for r in results if r["status"] in {"rebuilt", "dry_run"})
    print(json.dumps(
        {
            "mode": "execute" if args.execute else "dry-run",
            "bots": len(bot_ids),
            "rebuilt": rebuilt,
            "details": results,
        },
        ensure_ascii=False,
        indent=2,
        default=str,
    ))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
